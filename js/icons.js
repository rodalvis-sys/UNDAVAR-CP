// Sustituye cada <span data-icono="..."> por su SVG.
function pintarIconos(raiz = document) {
  raiz.querySelectorAll("[data-icono]").forEach((el) => {
    const nombre = el.dataset.icono;
    const dibujo = window.UNDAVAR_ICONOS[nombre];
    if (!dibujo) return;
    el.innerHTML = `<svg class="icono" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${dibujo}</svg>`;
  });
}

document.addEventListener("DOMContentLoaded", () => pintarIconos());
